#!/usr/bin/env python3
"""Generates insert_data.sql (synthetic data, fixed seed => reproducible).
Usage: python3 generate_data.py > insert_data.sql   (optional; insert_data.sql is already submitted)"""
import random
random.seed(2026)

modes = ["Domination", "Convoy", "Convergence"]
maps = [  # (name, mode_id)  -- last one intentionally never played
    ("Tokyo 2099: Shinjuku", 1), ("Klyntar", 1), ("Birnin T'Challa", 1),
    ("Yggdrasil Path", 2), ("Hellfire Gala: Krakoa", 2), ("Empire of Eternal Night: Midtown", 2),
    ("Sanctum Sanctorum", 3), ("Intergalactic Empire of Wakanda", 3), ("Hydra Charteris Base", 3)]
heroes = [
 ("Captain America","Vanguard"),("Hulk","Vanguard"),("Doctor Strange","Vanguard"),("Venom","Vanguard"),
 ("Magneto","Vanguard"),("Thor","Vanguard"),("Peni Parker","Vanguard"),
 ("Iron Man","Duelist"),("Spider-Man","Duelist"),("Black Panther","Duelist"),("Star-Lord","Duelist"),
 ("Hela","Duelist"),("Wolverine","Duelist"),("The Punisher","Duelist"),("Psylocke","Duelist"),("Storm","Duelist"),
 ("Luna Snow","Strategist"),("Mantis","Strategist"),("Rocket Raccoon","Strategist"),
 ("Jeff the Land Shark","Strategist"),("Adam Warlock","Strategist"),("Loki","Strategist"),
 ("Squirrel Girl","Duelist")]  # last hero intentionally never picked
tags = ["NovaStrike","QuantumFox","IronLark","SilentRaven","PixelBrawler","CosmicDrift","ArcLight77",
        "ShadowByte","TurboWidow","GammaGrunt","VoidWalker","LunaTide","RocketFuel","MidnightKrakoa",
        "SwiftSentinel","BlitzMantis","CasualCarl"]  # last player intentionally has no matches
role_of = {i+1: r for i, (_, r) in enumerate(heroes)}
by_role = {r: [i+1 for i, (_, rr) in enumerate(heroes) if rr == r and i+1 != len(heroes)]
           for r in ("Vanguard", "Duelist", "Strategist")}
active = list(range(1, len(tags)))  # player ids 1..16

def q(s): return "'" + s.replace("'", "''") + "'"
out = ["-- insert_data.sql: synthetic sample data (generated by generate_data.py)",
       "-- Run AFTER schema.sql.", "PRAGMA foreign_keys = ON;", "BEGIN TRANSACTION;", ""]
out.append("INSERT INTO game_mode (mode_id, mode_name) VALUES")
out.append(",\n".join(f"  ({i+1}, {q(m)})" for i, m in enumerate(modes)) + ";\n")
out.append("INSERT INTO map (map_id, map_name, mode_id) VALUES")
out.append(",\n".join(f"  ({i+1}, {q(n)}, {m})" for i, (n, m) in enumerate(maps)) + ";\n")
out.append("INSERT INTO hero (hero_id, hero_name, role) VALUES")
out.append(",\n".join(f"  ({i+1}, {q(n)}, {q(r)})" for i, (n, r) in enumerate(heroes)) + ";\n")
out.append("INSERT INTO player (player_id, gamertag, added_on) VALUES")
out.append(",\n".join(f"  ({i+1}, {q(t)}, '2026-{9 if i<8 else 10:02d}-{(i*2)%27+1:02d}')" for i, t in enumerate(tags)) + ";\n")

matches, teams, parts = [], [], []
for mid in range(1, 25):
    map_id = random.randint(1, len(maps) - 1)           # map 9 never played
    day = 1 + (mid - 1) * 20 // 24 + 1
    month = 9 if mid <= 12 else 10
    day = (mid * 2 - 1) if mid <= 12 else (mid - 12) * 2
    played = f"2026-{month:02d}-{day:02d} {random.randint(17,23):02d}:{random.choice([0,15,30,45]):02d}:00"
    dur = None if mid == 7 else random.randint(420, 1080)   # edge case: unknown duration
    matches.append(f"  ({mid}, {map_id}, {q(played)}, {'NULL' if dur is None else dur})")
    if mid == 12:   res = ("DRAW", "DRAW")
    else:           res = random.choice([("WIN", "LOSS"), ("LOSS", "WIN")])
    for t in (1, 2): teams.append(f"  ({mid}, {t}, {q(res[t-1])})")
    pool = random.sample(active, 12)
    for t in (1, 2):
        members = pool[(t-1)*6: t*6]
        if mid == 15 and t == 2: members = members[:5]   # edge case: a player left (5 v 6)
        nv, nd, ns = random.choice([(2,2,2),(2,2,2),(1,3,2),(3,1,2),(2,1,3),(1,2,3),(2,3,1)])  # varied team compositions
        comp = random.sample(by_role["Vanguard"], nv) + random.sample(by_role["Duelist"], nd) + random.sample(by_role["Strategist"], ns)
        # keep heroes distinct within a side; allow duplicates across sides
        won = res[t-1] == "WIN"
        for p, h in zip(members, comp):
            r = role_of[h]; k = 1.15 if won else 0.9
            kills = int(random.randint(4, 22) * k); deaths = random.randint(2, 14); assists = random.randint(2, 25)
            dmg = {"Vanguard": random.randint(6000, 14000), "Duelist": random.randint(9000, 24000), "Strategist": random.randint(4000, 11000)}[r]
            blk = random.randint(9000, 26000) if r == "Vanguard" else 0
            heal = random.randint(8000, 22000) if r == "Strategist" else 0
            parts.append(f"  ({mid}, {p}, {t}, {h}, {kills}, {deaths}, {assists}, {dmg}, {blk}, {heal})")
out.append("INSERT INTO match (match_id, map_id, played_at, duration_seconds) VALUES")
out.append(",\n".join(matches) + ";\n")
out.append("INSERT INTO match_team (match_id, team_number, result) VALUES")
out.append(",\n".join(teams) + ";\n")
out.append("INSERT INTO match_participant (match_id, player_id, team_number, hero_id, kills, deaths, assists, damage_dealt, damage_blocked, healing_done) VALUES")
out.append(",\n".join(parts) + ";\n")
out.append("COMMIT;")
print("\n".join(out))
